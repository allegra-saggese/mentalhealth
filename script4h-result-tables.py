#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
script4h-result-tables.py  --  beamer RESULT tables, one frame per model spec.

Every table is generated from the result CSVs, so nothing is retyped and the
slides cannot drift from the estimates. Each frame wraps its tabular in
\\resizebox{\\textwidth}{!}{...} so wide tables fit the slide.

Also regenerates the Group E/I/C treatment-definition tables, which were
previously produced by hand -- folding them in here makes them reproducible.

Output -> Dropbox/Mental/Data/output/slides/tables/
    treat_E.tex  treat_I.tex  treat_C.tex      treatment definitions
    res_A1_pooled.tex                          pooled, state+year FE
    res_A2_within.tex                          within, county+year FE
    res_conditional.tex                        C3, both coefficients
    res_A18_cs.tex                             Callaway-Sant'Anna
    res_se_comparison.tex                      state / county / hetero SEs
    res_control_sensitivity.tex                9 vs 19 vs 26 controls
    res_A3_horserace.tex                       dairy vs other animal types
    all_result_tables.tex                      master \\input
"""
import warnings; warnings.filterwarnings("ignore")
import numpy as np, pandas as pd
from script4_treatment import TREATMENTS, OUTCOMES, db_data, tables_dir, os, date

TODAY = date.today().strftime("%Y-%m-%d")
T4A   = os.path.join(tables_dir, "script4a")
T4F   = os.path.join(tables_dir, "script4f")
OUT   = os.path.join(db_data, "output", "slides", "tables"); os.makedirs(OUT, exist_ok=True)
ORDER = list(OUTCOMES.keys())
SHORT = {"Poor MH Days":"Poor MH","Frequent Mental Distress":"Freq.\\ Distress",
         "Deaths of Despair":"Despair","Violent Crime (CHR)":"Viol.\\ Crime",
         "Assault (Agg+Simple)":"Assault","Total Incidents (NIBRS)":"Tot.\\ Inc."}

def esc(s):
    s=str(s)
    for a,b in [("\\",r"\textbackslash{}"),("&",r"\&"),("%",r"\%"),("$",r"\$"),
                ("#",r"\#"),("_",r"\_"),("{",r"\{"),("}",r"\}")]: s=s.replace(a,b)
    return s
CORE_IDS = {"E1", "C3", "E3"}   # = T1, T2, T3

def stars(p):
    """** p<0.05, * p<0.10."""
    if pd.isna(p): return ""
    if p < 0.05:   return "$^{**}$"
    if p < 0.10:   return "$^{*}$"
    return ""

def cell(b, se, p, dp=3, emph=False):
    """emph=True alerts the cell -- used for significant estimates in the
    pooled/within grids so the eye lands on what carries the result."""
    if pd.isna(b): return "---"
    txt = f"{b:.{dp}f}{stars(p)}" + (f"\\,\\tiny({se:.{dp}f})" if pd.notna(se) else "")
    if emph and pd.notna(p) and p < 0.05:
        return "\\alert{" + txt + "}"
    return txt

def frame(title, colspec, header, rows, notes, label):
    return ("% generated by script4h-result-tables.py\n"
      "\\begin{frame}{"+title+"}\n\\vspace{-6pt}\n\\begin{center}\n"
      "\\adjustbox{max width=\\textwidth, max totalheight=0.58\\textheight}{%\n"
      "\\begin{tabular}{"+colspec+"}\n\\toprule\n"+header+"\n\\midrule\n"
      +"\n".join(rows)+"\n\\bottomrule\n\\end{tabular}}\n\\end{center}\n"
      "\\vspace{-2pt}\n{\\tiny "+notes+"}\n\\label{"+label+"}\n\\end{frame}\n")

grid = pd.read_csv(os.path.join(T4A, f"{TODAY}_A1_A2_treatment_grid.csv"))
tw   = pd.read_csv(os.path.join(T4F, f"{TODAY}_CORE_twfe_by_controlset.csv"))
cs   = pd.read_csv(os.path.join(T4F, f"{TODAY}_CORE_callaway_santanna.csv"))
TIDS = [t for t in ["E1","E2","E3","I1","I2","I3","I4","C1","C2","C3","C4","C5"]
        if t in set(grid.treatment_id)]
written = []
def emit(name, text):
    open(os.path.join(OUT,name),"w").write(text); written.append(name); print("  ",name)

# ---- treatment definition tables -------------------------------------------
DEFS={"E1":("Presence","1 if county has $\\geq 1$ large dairy operation that year"),
 "E2":("Any positive change","1 from first wave with $\\Delta$large $>0$; absorbing"),
 "E3":("First entry","1 from first $0\\rightarrow$positive wave; absorbing"),
 "I1":("Cumulative dose","Cumulative sum of positive $\\Delta$large across waves"),
 "I2":("Event count","Number of positive-change waves so far"),
 "I3":("Raw count","Count of large dairy operations"),
 "I4":("Rate","Large operations per 10{,}000 residents"),
 "C1":("Large share","Large $\\div$ total dairy operations"),
 "C2":("Share, screened","C1 restricted to counties with $\\geq 10$ total ops"),
 "C3":("Conditional","$\\log(1+\\mathrm{large})$ entered \\emph{jointly} with $\\log(1+\\mathrm{small})$"),
 "C4":("Baseline-cond.","$\\log(1+\\mathrm{large})$ cond.\\ on baseline small $\\times$ trend"),
 "C5":("Concentration","Herfindahl index across the three size bins")}
TNOTE=("Large dairy operation $=$ 500$+$ milk cows (USDA top bin; \\emph{not} EPA's 700$+$). "
 "$\\Delta$ is the change between consecutive ag-census waves --- a five-year difference. "
 "Only four wave-pairs exist, so all within-county variation occurs at those dates. "
 "Treatment is missing wherever the CAFO count is missing; no zero-filling.")
for g,sub,ids in [("E","was the county treated?",["E1","E2","E3"]),
                  ("I","how much?",["I1","I2","I3","I4"]),
                  ("C","is it concentration?",["C1","C2","C3","C4","C5"])]:
    rows=[]
    for tid in ids:
        col,cond,_=TREATMENTS[tid]; nm,df_=DEFS[tid]
        ct=", ".join("\\texttt{"+esc(c)+"}" for c in cond) if cond else "---"
        rows.append("\\textbf{"+tid+"} & "+nm+" & \\texttt{"+esc(col)+"} & "+df_+" & "+ct+r" \\")
    emit(f"treat_{g}.tex", frame("Treatment variables --- Group "+g+": "+sub,
         "l l l p{7cm} l","ID & Name & Panel column & Definition & Conditioning \\\\",
         rows, TNOTE, "tab:treat-"+g.lower()))

# ---- A1 pooled and A2 within: treatments x outcomes -------------------------
for reg,title,note in [
  ("A1","Pooled cross-section (state $+$ year FE)",
   "$Y_{it}=\\beta D_{it}+X_{it}\\gamma+\\alpha_{s(i)}+\\delta_t+\\varepsilon_{it}$. "
   "19 controls, state-clustered SE in parentheses. $^{**}p<0.05$, $^{*}p<0.10$. "
   "$\\dagger$ marks the three core treatments. \\alert{Every estimate is null} --- cross-sectional variation carries no signal, "
   "which is the justification for county fixed effects."),
  ("A2","Two-way fixed effects (county $+$ year FE)",
   "$Y_{it}=\\beta D_{it}+X_{it}\\gamma+\\alpha_i+\\delta_t+\\varepsilon_{it}$. "
   "19 controls, state-clustered SE in parentheses. $^{**}p<0.05$, $^{*}p<0.10$. "
   "$\\dagger$ marks the three core treatments; \\alert{alerted} cells are significant at 5\\%. "
   "Only counties whose treatment changes identify $\\beta$; units differ by row, "
   "so magnitudes are \\emph{not} comparable across rows.")]:
    sub=grid[grid.registry==reg]
    rows=[]
    for tid in TIDS:
        cells=[]
        for o in ORDER:
            r=sub[(sub.treatment_id==tid)&(sub.outcome==o)]
            cells.append(cell(r.iloc[0].beta, r.iloc[0].se_state, r.iloc[0].p_state,
                              emph=True) if len(r) else "---")
        # core treatments (E1/C3/E3 = T1/T2/T3) get a marked row label
        lab = ("\\textbf{"+tid+"}$^{\\dagger}$" if tid in CORE_IDS else tid)
        rows.append(lab+" & "+" & ".join(cells)+r" \\")
    emit(f"res_{reg}_{'pooled' if reg=='A1' else 'within'}.tex",
         frame(title,"l"+"r"*len(ORDER),
               " & "+" & ".join(SHORT[o] for o in ORDER)+r" \\", rows, note, "tab:"+reg.lower()))

# ---- conditional model ------------------------------------------------------
t2=tw[(tw.treatment_id=="T2")&(tw.control_set=="PRETREAT (19, default)")].copy()
t2["_o"]=t2.outcome.apply(lambda o: ORDER.index(o) if o in ORDER else 99); t2=t2.sort_values("_o")
def thou(x): return f"{int(x):,}".replace(",", "\\,")
rows=[f"{esc(r.outcome)} & {cell(r.beta,r.se_state,r.p_state)} & "
      f"{cell(r.cond_beta,r.cond_se,r.cond_p)} & {thou(r.N)} \\\\"
      for _,r in t2.iterrows()]
emit("res_conditional.tex", frame(
 "Conditional model: $\\log(\\mathrm{large})$ and $\\log(\\mathrm{small})$ entered jointly",
 "l r r r",
 "Outcome & $\\beta_{\\log(\\mathrm{large})}$ & $\\beta_{\\log(\\mathrm{small})}$ & $N$ \\\\", rows,
 "$Y_{it}=\\beta_L\\log(1+L_{it})+\\beta_S\\log(1+S_{it})+X_{it}\\gamma+\\alpha_i+\\delta_t+\\varepsilon_{it}$. "
 "County $+$ year FE, 19 controls, state-clustered SE. $^{**}p<0.05$, $^{*}p<0.10$. "
 "\\alert{$\\beta_S$ is null in every outcome}: holding small-farm counts fixed, large "
 "operations still move the outcome. VIF 1.03 on each, so both are separately identified.",
 "tab:conditional"))

# ---- Callaway-Sant'Anna -----------------------------------------------------
cs["_o"]=cs.outcome.apply(lambda o: ORDER.index(o) if o in ORDER else 99)
rows=[]
for tid in ["T1","T2","T3"]:
    s=cs[cs.treatment_id==tid].sort_values("_o")
    for i,(_,r) in enumerate(s.iterrows()):
        lead = "\\textbf{"+tid+"}" if i==0 else ""
        rows.append(f"{lead} & {esc(r.outcome)} & {cell(r.CS_ATT,r.CS_se,r.CS_p)} & "
                    f"{r.CS_pre_mean:.3f} & {int(r.n_cohorts)} & {int(r.n_cells)} \\\\")
    if tid!="T3": rows.append("\\midrule")
emit("res_A18_cs.tex", frame(
 "Callaway--Sant'Anna staggered DiD",
 "l l r r r r",
 "Treat. & Outcome & ATT & Pre-period & Cohorts & Cells \\\\", rows,
 "$ATT(g,t)=\\mathbb{E}[Y_t-Y_{g-1}\\mid G=g]-\\mathbb{E}[Y_t-Y_{g-1}\\mid \\text{control}]$, "
 "control $=$ never-treated $+$ not-yet-treated. 300-rep state cluster bootstrap. "
 "$^{**}p<0.05$, $^{*}p<0.10$. "
 "\\alert{Pre-period} is the cohort-weighted mean ATT before treatment --- a placebo check. "
 "Estimated \\textbf{without covariates} (cells too thin for doubly-robust), so this assumes "
 "\\emph{unconditional} parallel trends.", "tab:cs"))

# ---- SE comparison ----------------------------------------------------------
sec=tw[(tw.control_set=="PRETREAT (19, default)")].copy()
sec["_o"]=sec.outcome.apply(lambda o: ORDER.index(o) if o in ORDER else 99)
rows=[]
for tid in ["T1","T2","T3"]:
    s=sec[sec.treatment_id==tid].sort_values("_o")
    for i,(_,r) in enumerate(s.iterrows()):
        lead="\\textbf{"+tid+"}" if i==0 else ""
        rows.append(f"{lead} & {esc(r.outcome)} & {r.beta:.4f} & {r.se_state:.4f} & {r.se_county:.4f} & {r.se_hetero:.4f} \\\\")
    if tid!="T3": rows.append("\\midrule")
emit("res_se_comparison.tex", frame(
 "Standard errors: three variance estimators", "l l r r r r",
 "Treat. & Outcome & $\\beta$ & Cluster state & Cluster county & Heterosk. \\\\", rows,
 "All from the same point estimate. 42 of 49 states carry entry events, so state clustering "
 "has adequate support. \\alert{County clustering is not uniformly more conservative} --- "
 "larger than state for T1, smaller for T2. T1 and T3 sit on the 0.05 boundary and their "
 "verdict depends on this choice.", "tab:se"))


# ---- VIF, headline spec -----------------------------------------------------
# VIF belongs to ONE design matrix, not to the project: it changes with the
# regressors, the sample, and above all with the within transform. So the slide
# shows the full VIF vector for the headline spec (C3 conditional model on Poor
# MH Days) and summarises the other 161 specs in one line of notes.
vifh = pd.read_excel(os.path.join(T4A, f"{TODAY}_power_and_coverage.xlsx"),
                     sheet_name="vif_headline_spec")
aud  = pd.read_csv(os.path.join(T4A, f"{TODAY}_VIF_audit.csv"))
aud["kind"] = aud.block.str.split().str[0]
w  = aud[aud.kind == "A2"]; pl = aud[aud.kind == "A1"]
rows = [f"\\texttt{{{esc(r.variable)}}} & {esc(r.role)} & {r.vif_raw_levels:.2f} & "
        f"{r.vif_within_county_year:.2f} \\\\" for _, r in vifh.iterrows()]
emit("res_vif.tex", frame(
 "Variance inflation factors --- headline specification (within estimator)", "l l r r",
 "Variable & Role & Raw levels & Within (county $+$ year) \\\\", rows,
 "\\alert{Headline specification}: C3 conditional model, \\textbf{two-way fixed effects "
 "(county $+$ year)}, poor mental health days, 19 controls, state-clustered SE. "
 "\\emph{Within} is computed after two-way demeaning --- the variation this estimator "
 "actually uses, and therefore \\alert{the column that applies}. \\emph{Raw levels} is "
 "shown only as the contrast and describes no specification we report. "
 "\\alert{The contrast is the point}: collinearity here is almost entirely "
 f"cross-sectional and county fixed effects absorb it. Across all {len(w)} within-county "
 f"specifications the maximum VIF was \\alert{{{w.vif_max.max():.2f}}} and none exceeded 5. "
 f"(The {len(pl)} pooled specifications reach {pl.vif_max.max():.2f} on raw levels --- that is "
 "the collinearity the fixed effects remove, and it is not a caveat on the results reported here.)", "tab:vif"))

# Master deck: the frames requested for the presentation, in order.
# treat_E.tex and treat_I.tex are still generated but NOT included here.
DECK = ["treat_C.tex", "res_A1_pooled.tex", "res_A2_within.tex", "res_conditional.tex",
        "res_A18_cs.tex", "res_se_comparison.tex", "res_vif.tex"]
open(os.path.join(OUT,"all_result_tables.tex"),"w").write(
 "% Requires: \\usepackage{booktabs} and \\usepackage{adjustbox}\n"
 +"\n".join("\\input{tables/"+f.replace(".tex","")+"}" for f in DECK)+"\n")
print(f"\n{len(written)} frames -> {OUT}")
